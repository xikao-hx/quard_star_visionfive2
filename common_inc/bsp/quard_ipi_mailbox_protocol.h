#ifndef __QUARD_IPI_MAILBOX_PROTOCOL_H__
#define __QUARD_IPI_MAILBOX_PROTOCOL_H__

/* Shared-memory location and layout used by all AMP participants. */
#define IPI_MBOX_BASE			0x6e402000UL
#define IPI_MBOX_CHANS			2U
#define IPI_MBOX_PAYLOAD_SIZE		28U
#define IPI_MBOX_STATE_OFFSET		IPI_MBOX_PAYLOAD_SIZE
#define IPI_MBOX_CHAN_STRIDE		32U
#define IPI_MBOX_REQUIRED_SIZE		(IPI_MBOX_CHANS * IPI_MBOX_CHAN_STRIDE)

#define IPI_MBOX_TYPE_RX		0U
#define IPI_MBOX_TYPE_TX		1U
#define IPI_MBOX_LINUX_HART		1U

#define IPI_MBOX_STATE_IDLE		0U
#define IPI_MBOX_STATE_DATA_READY	1U
#define IPI_MBOX_STATE_ACK		2U

#define IPI_MBOX_RECOVERY_MS		20U

#endif /* __QUARD_IPI_MAILBOX_PROTOCOL_H__ */
